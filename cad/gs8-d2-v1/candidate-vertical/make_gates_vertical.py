"""Write GATES-VERTICAL.md from gate_map.py, the r7 build receipt and the r7 BX blocker list (review VN-50, FP-15).

CAD-free. Default: print the counts. --write: rewrite GATES-VERTICAL.md and the generated gates blocks in README.md and
REVIEW.md. --check: read-only, exit 1 when any of them is stale, a gate or BX item is unmapped or unknown, a disposition word is invalid, an r7-withdrawn gate
is not retired, or a named G-V-* gate is missing from REVIEW.md.
"""
from cv_io import read_text, write_text
from pathlib import Path
import argparse, collections, json, re, sys
import evidence_rules as ER
import gate_map as GM

HERE = Path(__file__).resolve().parent
DOC = 'GATES-VERTICAL.md'
BLOCK_DOCS = ('README.md', 'REVIEW.md')
BEGIN, END = '<!-- gates:begin (generated by make_gates_vertical.py; do not edit) -->', '<!-- gates:end -->'
R7_BLOCKERS = '../guide/BLOCKERS-2026-10-08.md'


def r7_gates(root=HERE):
    return json.loads(read_text((Path(root) / ER.R7_BUILD_RECEIPT).resolve()))['hardware_gates']['gates']


def r7_bx(root=HERE):
    text = read_text((Path(root) / R7_BLOCKERS).resolve())
    return {m.group(1): (m.group(2), m.group(3).strip()) for m in re.finditer(r'^\| (BX-\d+) \| (\w+) \| [^|]*\| ([^|]*)\|', text, re.M)}


def problems(root=HERE):
    root = Path(root)
    gates, bx = r7_gates(root), r7_bx(root)
    review = read_text(root / 'REVIEW.md')
    out = [('gate_unmapped', g) for g in sorted(set(gates) - set(GM.GATES))]
    out += [('gate_unknown', g) for g in sorted(set(GM.GATES) - set(gates))]
    out += [('bx_unmapped', b) for b in sorted(set(bx) - set(GM.BX))] + [('bx_unknown', b) for b in sorted(set(GM.BX) - set(bx))]
    for table, rows in (('gate', GM.GATES), ('bx', GM.BX)):
        out += [('bad_word', '%s %s %s' % (table, k, v[0])) for k, v in rows.items() if v[0] not in GM.WORDS]
        out += [('replaced_without_gate', k) for k, v in rows.items() if v[0] == 'replaced' and not (v[1] or '').startswith('G-V-')]
    out += [('withdrawn_not_retired', g) for g, s in gates.items() if s.startswith('withdrawn') and GM.GATES.get(g, ('',))[0] != 'retired']
    named = {w for v in list(GM.GATES.values()) + list(GM.BX.values()) for w in re.findall(r'G-V-[A-Z]+', v[1] or '')}
    out += [('g_v_unknown', g) for g in sorted(named - set(GM.G_V))]
    out += [('g_v_not_in_review', g) for g in GM.G_V if '| %s |' % g not in review]
    return out


def counts(root=HERE):
    gates = r7_gates(root)
    c = collections.Counter(GM.GATES[g][0] for g in gates if g in GM.GATES)
    open_r7 = [g for g, s in gates.items() if s.startswith('open')]
    still = [g for g in open_r7 if GM.GATES.get(g, ('',))[0] in ('carried', 're-scoped', 'replaced')]
    b = collections.Counter(v[0] for v in GM.BX.values())
    return dict(total=len(gates), open_r7=len(open_r7), by_word={w: c.get(w, 0) for w in GM.WORDS},
                open_r7_still_required=len(still), open_r7_retired=len(open_r7) - len(still),
                bx_total=len(GM.BX), bx_by_word={w: b.get(w, 0) for w in GM.WORDS})


def render(root=HERE):
    gates, bx, n = r7_gates(root), r7_bx(root), counts(root)
    word = lambda d: ', '.join('%d %s' % (d[w], w) for w in GM.WORDS)
    out = ['# r7 gates and BX fixes on the vertical candidate', '',
           'Generated by `make_gates_vertical.py` from `gate_map.py`, the r7 build receipt (`cad/gs8-d2-v1/out/build-receipt.json`, '
           'hardware_gates.gates) and `cad/gs8-d2-v1/guide/BLOCKERS-2026-10-08.md`; do not edit. Review 2026-10-10 VN-50.', '',
           'The disposition rules are in the `gate_map.py` docstring. No gate is closed by this table: carried, re-scoped and '
           'replaced gates all remain open physical gates, and the candidate adds its own G-V-* gates (REVIEW.md).', '',
           '## Counts', '',
           '- r7 receipt gates: %d (%d open in r7). Disposition on the candidate: %s.' % (n['total'], n['open_r7'], word(n['by_word'])),
           '- Of the %d gates open in r7, %d still apply to the candidate (carried, re-scoped or replaced by a G-V-* gate) and %d '
           'are retired with deleted parts (%s).' % (n['open_r7'], n['open_r7_still_required'], n['open_r7_retired'], ', '.join(GM.DELETED_PARTS)),
           '- r7 BX blocker fixes: %d. Disposition: %s.' % (n['bx_total'], word(n['bx_by_word'])), '',
           '## r7 physical gates', '', '| Gate | r7 status | Candidate | Carried by | Why |', '|---|---|---|---|---|']
    for g in sorted(gates, key=lambda s: (s.split('/')[0].rstrip('0123456789b'), len(s), s)):
        w, by, why = GM.GATES.get(g, ('UNMAPPED', None, ''))
        out.append('| %s | %s | %s | %s | %s |' % (g, gates[g], w, by or '-', why))
    out += ['', '## r7 BX blocker fixes', '', '| BX | r7 severity | Candidate | Where | Why |', '|---|---|---|---|---|']
    for b in sorted(GM.BX, key=lambda s: int(s.split('-')[1])):
        w, where, why = GM.BX[b]
        out.append('| %s | %s | %s | %s | %s |' % (b, bx.get(b, ('?', ''))[0], w, where or '-', why))
    return '\n'.join(out) + '\n'


def block(root=HERE):
    n = counts(root)
    return '\n'.join([BEGIN, '**r7 gates on this candidate (generated):** %d r7 receipt gates (%d open in r7): %s; %d of the open '
                      'ones still apply here (carried, re-scoped or replaced by a G-V-* gate), %d retired with deleted parts. '
                      'r7 BX fixes: %s. Table: [GATES-VERTICAL.md](GATES-VERTICAL.md).' % (
                          n['total'], n['open_r7'], ', '.join('%d %s' % (n['by_word'][w], w) for w in GM.WORDS),
                          n['open_r7_still_required'], n['open_r7_retired'],
                          ', '.join('%d %s' % (n['bx_by_word'][w], w) for w in GM.WORDS)), END])


def outputs(root=HERE):
    root = Path(root)
    out = {DOC: render(root)}
    blk = block(root)
    for name in BLOCK_DOCS:
        text = read_text(root / name)
        if BEGIN not in text or END not in text:
            raise ValueError('gates markers missing in ' + name)
        a = text.index(BEGIN); b = text.index(END, a) + len(END)
        out[name] = text[:a] + blk + text[b:]
    return out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__)
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    a = ap.parse_args(argv)
    bad = problems()
    out = outputs()
    if a.write and not bad:
        for name, text in out.items():
            write_text(HERE / name, text)
    if a.check:
        bad += [('stale_output', name) for name, text in out.items() if not (HERE / name).is_file() or read_text(HERE / name) != text]
    print(json.dumps(dict(counts=counts(), problems=bad), indent=2))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
