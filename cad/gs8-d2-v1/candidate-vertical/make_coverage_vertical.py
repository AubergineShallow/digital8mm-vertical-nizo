def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def load(p):
    return json.loads(read_text(p))


def counts(label, d):
    """{category: {status: n}} for one report."""
    out = collections.defaultdict(collections.Counter)
    if label == 'print':
        for cat, c in d['summary'].items():
            out[cat].update({k: v for k, v in c.items() if v})
        return out
    rows = d.get('checks') if label != 'mesh' and label != 'power_static' else d.get('rows')
    for r in rows:
        cat = r.get('category') or label
        out[cat][r['status']] += 1
    return out


def collect(root=HERE):
    root = Path(root)
    sel = root / SEL
    reports, missing = {}, []
    man = sel / 'manifest.json'
    msha = sha(man) if man.is_file() else None
    for label, (name, verifier) in REPORTS.items():
        p = sel / name
        if not p.is_file():
            missing.append(label)
            continue
        d = load(p)
        bound = d.get('manifest_sha256', d.get('mechanical_manifest_sha256'))
        vsha = d.get('verification_source_sha256', d.get('source_sha256'))
        reports[label] = dict(path=SEL + '/' + name, sha256=sha(p), counts=counts(label, d),
                              same_manifest=bound == msha, verifier=verifier,
                              verifier_current=(root / verifier).is_file() and vsha == sha(root / verifier))
    unclassified = sorted('%s/%s' % (l, c) for l, r in reports.items() for c in r['counts'] if (l, c) not in KIND)
    r7 = load((root / R7_CHECKS).resolve())
    r7_rows = {k: (len(v) if isinstance(v, (list, dict)) else 0) for k, v in r7['results'].items()}
    unmapped = sorted(set(r7_rows) - set(R7_MAP))
    stale_map = sorted(set(R7_MAP) - set(r7_rows))
    return dict(manifest_sha256=msha, reports=reports, missing=missing, unclassified=unclassified,
                r7=r7_rows, unmapped=unmapped, stale_map=stale_map)


def tally(reports, label=None):
    t = collections.defaultdict(collections.Counter)
    for l, r in reports.items():
        if label and l != label:
            continue
        for c, n in r['counts'].items():
            t[KIND.get((l, c), 'unclassified')].update(n)
    return t


def fmt(c):
    return ' / '.join('%d %s' % (c.get(s, 0), s) for s in STATUSES if c.get(s, 0) or s != 'stub')


def summary_lines(col):
    rep = col['reports']
    main = rep.get('main')
    lines = []
    if main:
        tot = collections.Counter()
        for n in main['counts'].values():
            tot.update(n)
        k = tally(rep, 'main')
        lines.append('- Main audit (`%s`, %d rows in %d categories): %s. By kind: geometric %s; bookkeeping %s; '
                     'coverage/state %s; analytical/declared %s.' % (
                         main['path'], sum(tot.values()), len(main['counts']), fmt(tot), fmt(k[GEO]), fmt(k[BOOK]),
                         fmt(k[COV]), fmt(k[ANA])))
    k = tally({l: r for l, r in rep.items() if l != 'main'})
    lines.append('- Batch reports (%s): geometric %s; coverage/state %s; analytical/declared %s.' % (
        ', '.join(l for l in rep if l != 'main'), fmt(k[GEO]), fmt(k[COV]), fmt(k[ANA])))
    words = collections.Counter(w for _, w in R7_MAP.values())
    lines.append('- r7 categories (`cad/gs8-d2-v1/out/checks.json`, %d): %s.' % (
        len(col['r7']), ', '.join('%d %s' % (words[w], w) for w in ('ported', 'partly', 'report only', 'not ported'))))
    stale = [l for l, r in rep.items() if not (r['same_manifest'] and r['verifier_current'])]
    lines.append('- Report freshness: %s.' % ('every counted report binds the selected manifest and its current verifier'
                                              if not stale else 'stale (manifest or verifier changed since the report): '
                                              + ', '.join(stale) + '; the counts are what those reports hold'))
    lines.append('- Per-category table and the r7 mapping: [COVERAGE-VERTICAL.md](COVERAGE-VERTICAL.md).')
    return lines


def render_doc(col):
    rep = col['reports']
    out = ['# Check coverage of the vertical candidate', '',
           'Generated by `make_coverage_vertical.py` from the selected compact-Kowa reports (manifest `%s`); do not edit. '
           'Regenerate with `make_coverage_vertical.py --write` after every report refresh; `--check` fails when this '
           'file is stale. Review 2026-10-10 VN-21.' % (col['manifest_sha256'] or 'missing'), '',
           '## Summary', ''] + summary_lines(col) + ['', '## Per report and category', '',
           '| Report | Category | Kind | pass | fail | info | stub |', '|---|---|---|---|---|---|---|']
    for l, r in rep.items():
        for c in sorted(r['counts']):
            n = r['counts'][c]
            kind = KIND.get((l, c), 'UNCLASSIFIED')
            note = KIND_NOTE.get((l, c))
            out.append('| %s | %s | %s%s | %d | %d | %d | %d |' % (l, c, kind, ' (%s)' % note if note else '',
                                                                 n.get('pass', 0), n.get('fail', 0), n.get('info', 0), n.get('stub', 0)))
    out += ['', '## Reports read', '', '| Report | File | Binds selected manifest | Verifier current |', '|---|---|---|---|']
    for l, r in rep.items():
        out.append('| %s | `%s` | %s | %s (`%s`) |' % (l, r['path'], 'yes' if r['same_manifest'] else 'no',
                                                     'yes' if r['verifier_current'] else 'no', r['verifier']))
    for l in col['missing']:
        out.append('| %s | missing | - | - |' % l)
    out += ['', '## r7 categories', '',
            'Each category of the r7 release check (`cad/gs8-d2-v1/out/checks.json`, row counts from that file) and where '
            'the candidate runs it. "partly" means a narrower candidate check stands in; "not ported" means the candidate '
            'has no equivalent and its geometry is not checked for that rule.', '',
            '| r7 category | r7 rows | Candidate | Coverage |', '|---|---|---|---|']
    for c in sorted(col['r7']):
        where, word = R7_MAP.get(c, (None, 'UNMAPPED'))
        out.append('| %s | %d | %s | %s |' % (c, col['r7'][c], where or '-', word))
    new = sorted('%s/%s' % (l, c) for l, r in rep.items() for c in r['counts']
                 if not any(w and w.split(' ')[0] == '%s/%s' % (l, c) for w, _ in R7_MAP.values()))
    out += ['', 'Candidate categories with no r7 counterpart: ' + ', '.join(new) + '.', '']
    return '\n'.join(out)


def block(col):
    return '\n'.join([BEGIN, '**Check coverage (generated):**', ''] + summary_lines(col) + [END])


def with_block(text, blk):
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        return text[:a] + blk + text[b:]
    raise ValueError('coverage markers missing')


def checkpoint(root, col):
    p = Path(root) / 'CHECKPOINT-STATUS.json'
    d = load(p)
    main = col['reports'].get('main')
    if main:
        tot = collections.Counter()
        for n in main['counts'].values():
            tot.update(n)
        d['main_summary'] = {s: tot.get(s, 0) for s in ('pass', 'fail', 'info')}
    plenum = Path(root) / SEL / 'shadow-plenum-checks.json'
    if plenum.is_file() and isinstance(load(plenum).get('summary'), dict):
        d['plenum_summary'] = load(plenum)['summary']    # the docs audit compares this field with the same source
    d['check_coverage'] = dict(
        generator='make_coverage_vertical.py', table=DOC,
        by_kind={l: {k: dict(v) for k, v in sorted(tally(col['reports'], l).items())} for l in col['reports']},
        r7_categories={w: sorted(c for c, (_, ww) in R7_MAP.items() if ww == w) for w in ('ported', 'partly', 'report only', 'not ported')})
    # FX-D (2026-10-11): the current reconciler's hash, kept apart from evidence_reconciler_that_wrote_current_evidence
    # (the reconciler recorded inside selected_evidence); the docs audit checks both pairs (checkpoint_hash).
    d['current_evidence_reconciler'] = {'path': RECONCILER, 'sha256': sha(Path(root) / RECONCILER),
                                        'generator': 'make_coverage_vertical.py'}
    return json.dumps(d, indent=2) + '\n'


def outputs(root=HERE):
    root = Path(root)
    col = collect(root)
    out = {DOC: render_doc(col), 'CHECKPOINT-STATUS.json': checkpoint(root, col)}
    blk = block(col)
    for n in BLOCK_DOCS:
        out[n] = with_block(read_text(root / n), blk)
    return col, out


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    ap.add_argument('--root', type=Path, default=HERE)
    a = ap.parse_args(argv)
    col, out = outputs(a.root)
    problems = [('unclassified', x) for x in col['unclassified']] + [('r7_unmapped', x) for x in col['unmapped']] + \
               [('r7_map_stale', x) for x in col['stale_map']] + [('missing_report', x) for x in col['missing']]
    if a.write and not problems:
        for n, t in out.items():
            write_text(a.root / n, t)
    stale = [n for n, t in out.items() if not (a.root / n).is_file() or read_text(a.root / n) != t]
    if a.check:
        problems += [('stale_output', n) for n in stale]
    print(json.dumps(dict(problems=problems, stale_outputs=stale if not a.write else [], summary=summary_lines(col)), indent=2))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
